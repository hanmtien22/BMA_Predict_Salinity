"""Fit the browser's teaching model from reproducible, fully synthetic observations."""

from pathlib import Path

import numpy as np


def fit():
    rng = np.random.default_rng(2020)
    n = 720
    day = rng.integers(1, 366, n)
    ndvi, ndwi = rng.uniform(-1, 1, (2, n))
    phase = 2 * np.pi * (day - 1) / 365
    x = np.column_stack([np.ones(n), np.sin(phase), np.cos(phase), ndvi, ndwi])
    # Assumed relationships for illustration, not estimated physical effects.
    y = x @ [12, 4, 1.5, -2.4, -3.2] + rng.normal(0, 0.9, n)
    return np.linalg.lstsq(x, y, rcond=None)[0]


if __name__ == "__main__":
    values = ", ".join(f"{number:.9f}" for number in fit())
    output = Path(__file__).resolve().parents[1] / "demo" / "coefficients.mjs"
    output.write_text(f"// Generated by scripts/train_demo.py\nexport default [{values}];\n",
                      encoding="utf-8", newline="\n")
